    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int row = tblMeja.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih meja dulu!");
            return;
        }

        String tableId = tblMeja.getModel().getValueAt(row, 0).toString();
        String nomorMeja = tblMeja.getModel().getValueAt(row, 1).toString();

        String[] pilihan = {"available", "reserved", "occupied"};
        String newStatus = (String) JOptionPane.showInputDialog(
                this,
                "Pilih status baru untuk Meja " + nomorMeja + ":",
                "Update Status Meja",
                JOptionPane.QUESTION_MESSAGE,
                null,
                pilihan,
                pilihan[0]
        );

        if (newStatus == null) {
            return;
        }

        String response = TCPClient.sendCommand(
                "UPDATE_TABLE~" + tableId + "~" + newStatus);

        if (response != null && response.equals("SUCCESS")) {
            JOptionPane.showMessageDialog(this, "Status meja berhasil diupdate!");
            refreshTable();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Gagal update status meja!", "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

