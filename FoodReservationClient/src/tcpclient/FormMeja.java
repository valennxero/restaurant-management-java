    private void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) tblMeja.getModel();
        model.setRowCount(0);

        String response = TCPClient.sendCommand("GET_TABLE");
        if (response == null || response.contains("KOSONG")) {
            return;
        }

        String[] parts = response.split("~");
        // Format: id|tableNumber|capacity|status
        for (int i = 1; i < parts.length; i++) {
            String[] cols = parts[i].split("\\|");
            if (cols.length >= 4) {
                model.addRow(new Object[]{
                    cols[0],//id
                    cols[1],//no meja
                    cols[2],//kapasitas
                    cols[3]//status
                });
            }
        }
    }

