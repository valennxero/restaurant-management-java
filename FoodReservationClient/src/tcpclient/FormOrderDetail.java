    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int row = tblOrder.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Pilih item pesanan dulu!");
            return;
        }

        String orderId = tblOrder.getModel().getValueAt(row, 0).toString();

        // Pilih status baru dari daftar
        String[] pilihan = {"Pending", "Preparing", "Ready", "Served"};
        String newStatus = (String) JOptionPane.showInputDialog(
                this,
                "Pilih status baru:",
                "Update Status Pesanan",
                JOptionPane.QUESTION_MESSAGE,
                null,
                pilihan,
                pilihan[0]
        );

        if (newStatus == null) {
            return;
        }

        String response = TCPClient.sendCommand(
                "UPDATE_ORDER~" + orderId + "~" + newStatus);

        if (response != null && response.equals("SUCCESS")) {
            JOptionPane.showMessageDialog(this, "Status berhasil diupdate!");
            refreshOrders();
        } else {
            JOptionPane.showMessageDialog(this, "Gagal update status!",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

