    private void refreshOrders() {
        DefaultTableModel model = (DefaultTableModel) tblOrder.getModel();
        model.setRowCount(0);

        String response = TCPClient.sendCommand("GET_ORDER~" + reservationId);
        if (response == null || response.contains("KOSONG")) {
            lblTotal.setText("Total: Rp 0");
            return;
        }

        String[] parts = response.split("~");
        double total = 0;

        for (int i = 1; i < parts.length; i++) {
            String[] cols = parts[i].split("\\|");
            //format: id|namaMenu|qty|harga|status
            if (cols.length >= 5) {
                double harga = Double.parseDouble(cols[3]);
                int qty = Integer.parseInt(cols[2]);
                double subtotal = harga * qty;
                total += subtotal;

                model.addRow(new Object[]{
                    cols[0], //id orderan
                    cols[1], //nama menu
                    cols[2], //jumlh
                    "Rp " + cols[3], //harga
                    cols[4] //status
                });
            }
        }
        lblTotal.setText("Total: Rp " + total);
    }

